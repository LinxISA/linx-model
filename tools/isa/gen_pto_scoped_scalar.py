#!/usr/bin/env python3
"""Generate model codec provenance for the signed PTO v0.59.1.0 carrier."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from gen_minst_codec import EXPECTED_CATALOG_CONTENT_SHA256, trace_uid_for


ROOT = Path(__file__).resolve().parents[2]
SCOPED_SOURCE_SHA256 = "0f9ab05d6a7547d970b8f2a21b158a5b993527df42445ab494ed8acea0462c16"


def read_locked(path: Path, expected: str) -> dict:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError(f"unexpected authority hash for {path}")
    return json.loads(data)


def build(authority: Path) -> tuple[str, str, str]:
    base = read_locked(authority / "isa/v0.58/linxisa-v0.58.json", EXPECTED_CATALOG_CONTENT_SHA256)
    source = read_locked(authority / "isa/v0.59/state/pto_scalar_forms.json", SCOPED_SOURCE_SHA256)
    forms = {
        row["pto_source_form_id"]: row for row in base["instructions"] if "pto_source_form_id" in row
    }
    variants = source["scoped_forms"]
    if len(variants) != 705 or len({row["form_id"] for row in variants}) != 705:
        raise ValueError("expected 705 unique scoped forms")
    uids = sorted({trace_uid_for(forms[row["base_form_id"]]) for row in variants})
    if len(uids) != 235:
        raise ValueError("expected 235 unique inner-form bindings")
    prefix = "// Generated by tools/isa/gen_pto_scoped_scalar.py from the locked PTO v0.59.1.0 projection."
    table = [prefix, "constexpr std::string_view kScopedInnerUids[] = {"]
    table.extend(f'    "{uid}",' for uid in uids)
    table.append("};")
    tests = [prefix, "constexpr ScopedWitness kScopedWitnesses[] = {"]
    for row in sorted(variants, key=lambda item: item["form_id"]):
        low, high = row["encoding"]
        if [(part["index"], part["width_bits"]) for part in (low, high)] != [(0, 32), (1, 32)]:
            raise ValueError(f"unexpected carrier parts for {row['form_id']}")
        word = int(low["match"], 0) | (int(high["match"], 0) << 32)
        inner = forms[row["base_form_id"]]
        if inner["length_bits"] != row["inner_length_bits"]:
            raise ValueError(f"unexpected inner width for {row['form_id']}")
        tests.append(
            f'    {{0x{word:016x}ULL, "{trace_uid_for(inner)}", {row["scope_code"]}, {inner["length_bits"]}}},'
        )
    tests.append("};")
    eligible = []
    scalar_forms = {row["form_id"]: row for row in source["forms"]}
    for identity in sorted({row["base_form_id"] for row in variants}):
        row = scalar_forms[identity]
        agu = row.get("agu", {})
        if (
            agu.get("action") not in {"Load", "Store"}
            or agu.get("address_kind") not in {"Immediate", "PCRelative"}
            or agu.get("update_mode") != "None"
        ):
            continue
        inner = forms[identity]
        eligible.append(
            (
                trace_uid_for(inner),
                agu["action"] == "Load",
                agu["address_kind"] == "PCRelative",
                agu["offset_scale"],
                agu["size_bytes"],
                agu["signed_load"],
            )
        )
    if len(eligible) != 60:
        raise ValueError(f"expected 60 scoped immediate/PCR single-access forms, found {len(eligible)}")
    runtime = [prefix, "constexpr ScopedSingleAccessForm kScopedSingleAccessForms[] = {"]
    runtime.extend(
        f'    {{"{uid}", {str(load).lower()}, {str(pcr).lower()}, {scale}, {size}, '
        f'{str(signed).lower()}}},'
        for uid, load, pcr, scale, size, signed in sorted(eligible)
    )
    runtime.append("};")
    return "\n".join(table) + "\n", "\n".join(tests) + "\n", "\n".join(runtime) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--authority-root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    paths = (
        "src/isa/pto_scoped_scalar_uids.inc",
        "tests/unit/pto_scoped_scalar_witnesses.inc",
        "src/emulator/pto_scoped_scalar_runtime.inc",
    )
    for name, expected in zip(paths, build(args.authority_root), strict=True):
        path = ROOT / name
        if args.check:
            if path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"stale PTO scoped codec output: {path}")
        else:
            path.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
